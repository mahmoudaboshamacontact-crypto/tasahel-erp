-- سجل خطوات تيكت الاستلام وربطها بالمعاملة الناتجة بعد التحويل.
-- Idempotent. لا يشغّل تلقائياً؛ يراجع ثم يُشغّل يدوياً.

create table if not exists public.pickup_ticket_action_history (
  id bigint generated by default as identity primary key,
  ticket_id bigint not null references public.pickup_tickets(id) on delete restrict,
  courier_id bigint not null references public.couriers(id) on delete restrict,
  step text not null check (step in ('accepted','call_attempt','on_the_way','waiting','papers_received')),
  transaction_id text,
  mission_id bigint references public.courier_trips(id) on delete set null,
  created_by uuid,
  created_at timestamptz not null default now()
);

create index if not exists pickup_ticket_action_history_ticket_idx
  on public.pickup_ticket_action_history(ticket_id, created_at);

create index if not exists pickup_ticket_action_history_tx_idx
  on public.pickup_ticket_action_history(transaction_id, created_at);

alter table public.pickup_ticket_action_history enable row level security;
revoke all on public.pickup_ticket_action_history from public, anon, authenticated;
grant select on public.pickup_ticket_action_history to authenticated;

drop policy if exists pickup_ticket_action_history_select on public.pickup_ticket_action_history;
create policy pickup_ticket_action_history_select
on public.pickup_ticket_action_history
for select to authenticated
using (
  public.is_manager()
  or public.is_staff()
  or exists (
    select 1 from public.couriers c
    where c.id = pickup_ticket_action_history.courier_id
      and c.user_id = (select auth.uid())
      and c.active = true
  )
);

create or replace function public.courier_ticket_set_step(p_ticket_id bigint, p_step text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_c public.couriers;
  v_t public.pickup_tickets;
  v_step text := btrim(coalesce(p_step, ''));
  v_steps text[] := array['accepted','call_attempt','on_the_way','waiting','papers_received'];
  v_cur_i integer;
  v_new_i integer;
  v_now timestamptz := now();
  v_cnt integer := 0;
begin
  if not public.is_courier() then
    raise exception 'الإجراء ده متاح للمندوب فقط' using errcode = '42501';
  end if;

  select * into v_c
  from public.couriers
  where user_id = (select auth.uid()) and active = true
  limit 1;

  if v_c.id is null then
    raise exception 'حساب المندوب غير مربوط أو غير نشط' using errcode = '42501';
  end if;

  v_new_i := array_position(v_steps, v_step);
  if v_new_i is null then
    raise exception 'خطوة غير صالحة (%)', v_step using errcode = '22023';
  end if;

  select * into v_t
  from public.pickup_tickets
  where id = p_ticket_id
  for update;

  if v_t.id is null then
    raise exception 'التيكت غير موجود' using errcode = 'P0002';
  end if;
  if v_t.courier_id is distinct from v_c.id then
    raise exception 'التيكت ده مش متعيّن لحضرتك' using errcode = '42501';
  end if;
  if v_t.status <> 'with_courier' then
    raise exception 'التيكت غير نشط عند المندوب حالياً (الحالة: %)', v_t.status using errcode = '22023';
  end if;

  if v_t.courier_step is null then
    if v_step <> 'accepted' then
      raise exception 'لازم تأكّد استلام التيكت أولاً قبل الخطوة دي' using errcode = '22023';
    end if;
  else
    v_cur_i := array_position(v_steps, v_t.courier_step);
    if v_new_i = v_cur_i then
      raise exception 'الخطوة دي متسجلة بالفعل' using errcode = '22023';
    elsif v_new_i < v_cur_i then
      raise exception 'مينفعش ترجع لخطوة سابقة' using errcode = '22023';
    elsif v_new_i > v_cur_i + 1 then
      raise exception 'لازم تمشي بالترتيب — سجّل الخطوة السابقة أولاً' using errcode = '22023';
    end if;
  end if;

  perform set_config('app.pt_trusted', '1', true);
  update public.pickup_tickets
  set courier_step = v_step, courier_step_at = v_now
  where id = p_ticket_id
    and courier_id = v_c.id
    and status = 'with_courier';

  get diagnostics v_cnt = row_count;
  if v_cnt = 0 then
    raise exception 'تعذر تحديث حالة التيكت — حاول تاني' using errcode = '40001';
  end if;

  insert into public.pickup_ticket_action_history
    (ticket_id, courier_id, step, created_by, created_at)
  values
    (p_ticket_id, v_c.id, v_step, (select auth.uid()), v_now);

  return jsonb_build_object('ok', true, 'step', v_step, 'at', v_now);
end;
$$;

revoke all on function public.courier_ticket_set_step(bigint,text) from public, anon;
grant execute on function public.courier_ticket_set_step(bigint,text) to authenticated;

create or replace function public.link_pickup_ticket_actions_to_transaction()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.status = 'converted'
     and old.status is distinct from 'converted'
     and new.converted_tx_id is not null
     and new.mission_id is not null then
    update public.pickup_ticket_action_history
       set transaction_id = new.converted_tx_id,
           mission_id = new.mission_id
     where ticket_id = new.id;

    update public.courier_contact_log
       set transaction_id = new.converted_tx_id
     where ticket_id = new.id
       and transaction_id is distinct from new.converted_tx_id;
  end if;
  return new;
end;
$$;

drop trigger if exists trg_link_pickup_ticket_actions_to_transaction on public.pickup_tickets;
create trigger trg_link_pickup_ticket_actions_to_transaction
after update of status, converted_tx_id, mission_id on public.pickup_tickets
for each row execute function public.link_pickup_ticket_actions_to_transaction();

revoke all on function public.link_pickup_ticket_actions_to_transaction() from public, anon, authenticated;
